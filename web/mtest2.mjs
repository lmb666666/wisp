import { chromium } from "@playwright/test";
const b = await chromium.launch({ args: ["--autoplay-policy=no-user-gesture-required"] });
const ctx = await b.newContext({ locale: "zh-CN", viewport: { width: 390, height: 900 }, deviceScaleFactor: 2 });
const p = await ctx.newPage();
await p.goto("http://localhost:18300/login");
await p.getByLabel("用户名").fill("liang");
await p.getByLabel("密码").fill("password123");
const init = await p.getByRole("button", { name: "创建并登录" }).isVisible().catch(() => false);
await p.getByRole("button", { name: init ? "创建并登录" : "登录", exact: true }).click();
await p.waitForURL(u => !u.pathname.startsWith("/login"));
await p.waitForTimeout(900);
await p.getByRole("button", { name: "网易云音乐" }).click();
await p.waitForTimeout(250);
await p.getByRole("textbox", { name: "链接" }).fill("https://music.163.com/song?id=1868553");
await p.getByRole("button", { name: "添加", exact: true }).click();
await p.getByRole("button", { name: "发布" }).click();
await p.waitForTimeout(2600);
await p.getByRole("button", { name: "播放" }).click();
await p.waitForTimeout(700);
const state = await p.evaluate(() => {
  const a = document.querySelector("audio");
  return a ? { paused: a.paused, current: +a.currentTime.toFixed(2), duration: a.duration } : null;
});
console.log("audio:", JSON.stringify(state));
console.log("pause btn visible:", await p.getByRole("button", { name: "暂停" }).isVisible().catch(() => false));
await p.screenshot({ path: "/tmp/shots/music-card.png" });
await b.close();
